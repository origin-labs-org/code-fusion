function padDatePart(value: number): string {
  return value.toString().padStart(2, "0");
}

function formatCfAgentLogDate(now: Date): string {
  return [now.getFullYear(), padDatePart(now.getMonth() + 1), padDatePart(now.getDate())].join("-");
}

function resolveCfAgentCurrentLogFilePath(now = new Date()): string {
  const configuredLogDir = process.env.CF_LOG_DIR?.trim();
  const logDir = configuredLogDir || join(homedir(), ".cf", "cli", "log");
  return join(logDir, `cf-${formatCfAgentLogDate(now)}.jsonl`);
}

