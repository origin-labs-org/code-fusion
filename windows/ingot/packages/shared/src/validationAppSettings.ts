const cfEndpointOriginSchema = z.preprocess((value) => {
  if (typeof value !== "string") {
    return undefined;
  }
  const trimmed = value.trim();
  if (!trimmed) {
    return undefined;
  }
  try {
    return normalizeCfEndpointOrigin(trimmed);
  } catch {
    return undefined;
  }
}, z.string().optional());

function sanitizeCfEndpointOrigin(value: unknown): unknown {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return value;
  }
  const raw = value as Record<string, unknown>;
  if (!("cfEndpointOrigin" in raw)) {
    return value;
  }
  const parsed = cfEndpointOriginSchema.safeParse(raw.cfEndpointOrigin);
  if (parsed.success && typeof parsed.data === "string") {
    return { ...raw, cfEndpointOrigin: parsed.data };
  }
  const { cfEndpointOrigin: _cfEndpointOrigin, ...next } = raw;
  return next;
}

